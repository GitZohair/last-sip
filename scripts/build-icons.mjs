// Extracts the game-icons.net (CC BY 3.0, via @iconify-json/game-icons) glyphs we use into src/game/icons.js.
// Run: node scripts/build-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
const set = JSON.parse(readFileSync(new URL('../node_modules/@iconify-json/game-icons/icons.json', import.meta.url)));
const MAP = {
  bomb: 'falling-bomb', carpet: 'carpet-bombing', banana: 'banana-peel', balls: 'beach-ball', ducks: 'duck', cans: 'soda-can',
  gust: 'wind-slap', mop: 'water-drop', lights: 'flashlight', bass: 'sound-waves', drunk: 'spiral-bottle', hyper: 'coffee-cup',
  fog: 'toaster', steady: 'shaking-hands', mopup: 'broom', pillows: 'pillow', fridge: 'fridge', fridges: 'fridge', moon: 'moon',
  tilt: 'perspective-dice-six-faces-random', tiny: 'ant', bigglass: 'beer-stein', disco: 'glass-ball', lid: 'checked-shield',
  refill: 'water-bottle', slowmo: 'hourglass', lava: 'lava', mirror: 'mirror-mirror', nuke: 'mushroom-cloud', fullrefill: 'big-wave',
  wanted: 'wanted-reward', trophy: 'trophy', crown: 'crown', mic: 'microphone', stopwatch: 'stopwatch', splash: 'splash',
  catch: 'hand', house: 'house', chat: 'talk', vacuum: 'vacuum-cleaner', fire: 'fire', run: 'run', streak: 'flame', duck: 'duck',
  door: 'door', lamp: 'desk-lamp', books: 'bookshelf', cabinet: 'robot-grab', conveyor: 'belt', glass: 'glass-heart',
  warning: 'hazard-sign', twitch: 'gamepad', cannon: 'cannon', barrel: 'barrel', bits: 'cut-diamond', sub: 'star-medal', raid: 'swords-emblem', follow: 'heart-plus',
};
const out = {}, missing = [];
for (const [k, name] of Object.entries(MAP)) { const ic = set.icons[name]; if (!ic) { missing.push(name); continue; } out[k] = ic.body; }
if (missing.length) { console.error('missing:', missing.join(', ')); process.exit(1); }
writeFileSync(new URL('../src/game/icons.js', import.meta.url),
`// Generated by scripts/build-icons.mjs from game-icons.net (CC BY 3.0, Lorc, Delapouite & contributors). Do not edit.
const B = ${JSON.stringify(out)};
export const icon = (name, cls = 'ico') => B[name] ? \`<svg class="\${cls}" viewBox="0 0 512 512" aria-hidden="true">\${B[name]}</svg>\` : '';
`);
console.log('icons:', Object.keys(out).length);
